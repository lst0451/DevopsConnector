import { AsyncLocalStorage } from 'node:async_hooks';

export type Language = 'zh-CN' | 'en';
const scope = new AsyncLocalStorage<Language>();
let preference: Language = 'zh-CN';

export function setLanguage(language: Language): void { preference = language; }
export function language(): Language { return scope.getStore() ?? preference; }
export function withLanguage<T>(value: Language, action: () => T): T { return scope.run(value, action); }

