export function t(message: keyof typeof english, locale = language()): string {
  return locale === 'en' ? english[message] : message;
}

// Previous releases persisted human-readable error messages in the sync state.
export function localizeStoredError(message: string): string {
  for (const [zh, en] of Object.entries(english)) {
    if (message === zh || message === en) { return language() === 'en' ? en : zh; }
  }
  const http = /^(图片下载失败，HTTP |Azure DevOps 请求失败，HTTP |Image download failed with HTTP |Azure DevOps request failed with HTTP )(\d{3})[.。]$/.exec(message);
  if (!http) { return message; }
  const image = http[1]!.startsWith('图片') || http[1]!.startsWith('Image');
  return t(image ? '图片下载失败，HTTP ' : 'Azure DevOps 请求失败，HTTP ') + http[2] + t('。');
}
